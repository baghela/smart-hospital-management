"""Laboratory orders, specimen tracking and results."""
from __future__ import annotations

from typing import List

from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.audit import logger as audit
from backend.auth.rbac import CurrentUser, enforce_patient_scope
from backend.core.errors import NotFoundError, ValidationError
from backend.models import LabOrder, LabOrderStatus, Patient
from backend.services.common import next_reference, utcnow

TEST_CATALOG = {
    "CBC": ("Complete Blood Count", 350.0),
    "LFT": ("Liver Function Test", 700.0),
    "KFT": ("Kidney Function Test", 750.0),
    "LIPID": ("Lipid Profile", 900.0),
    "HBA1C": ("HbA1c", 600.0),
    "TSH": ("Thyroid Stimulating Hormone", 450.0),
}

_ALLOWED_TRANSITIONS = {
    LabOrderStatus.ORDERED.value: {LabOrderStatus.COLLECTED.value, LabOrderStatus.CANCELLED.value},
    LabOrderStatus.COLLECTED.value: {LabOrderStatus.IN_PROGRESS.value, LabOrderStatus.CANCELLED.value},
    LabOrderStatus.IN_PROGRESS.value: {LabOrderStatus.RESULTED.value},
    LabOrderStatus.RESULTED.value: set(),
    LabOrderStatus.CANCELLED.value: set(),
}


def order_test(session: Session, user: CurrentUser, *, patient_id: int, test_code: str) -> LabOrder:
    user.require("lab:write")
    enforce_patient_scope(user, patient_id)
    if not session.get(Patient, patient_id):
        raise NotFoundError(f"Patient {patient_id} not found.")
    code = test_code.strip().upper()
    if code not in TEST_CATALOG:
        raise ValidationError(f"Unknown test '{code}'. Available: {', '.join(TEST_CATALOG)}")

    name, price = TEST_CATALOG[code]
    order = LabOrder(
        reference=next_reference(session, LabOrder, LabOrder.reference, "LAB"),
        patient_id=patient_id,
        ordered_by=user.username,
        test_code=code,
        test_name=name,
        price=price,
    )
    session.add(order)
    session.flush()
    audit.record(
        session,
        actor=user.username,
        actor_role=user.role.value,
        action="lab_order",
        resource="lab_order",
        resource_id=order.id,
    )
    session.commit()
    return order


def _transition(order: LabOrder, new_status: str) -> None:
    if new_status not in _ALLOWED_TRANSITIONS[order.status]:
        raise ValidationError(f"Cannot move lab order from '{order.status}' to '{new_status}'.")
    order.status = new_status


def collect_specimen(session: Session, user: CurrentUser, order_id: int) -> LabOrder:
    user.require("lab:write")
    order = get_order(session, user, order_id)
    _transition(order, LabOrderStatus.COLLECTED.value)
    order.specimen_id = f"SPC-{order.id:06d}"
    order.collected_at = utcnow()
    audit.record(
        session,
        actor=user.username,
        actor_role=user.role.value,
        action="lab_collect",
        resource="lab_order",
        resource_id=order.id,
    )
    session.commit()
    return order


def start_processing(session: Session, user: CurrentUser, order_id: int) -> LabOrder:
    user.require("lab:write")
    order = get_order(session, user, order_id)
    _transition(order, LabOrderStatus.IN_PROGRESS.value)
    session.commit()
    return order


def record_result(
    session: Session, user: CurrentUser, order_id: int, *, value: str, notes: str = ""
) -> LabOrder:
    """Results are entered by authorised lab staff - never generated by AI."""
    user.require("lab:write")
    order = get_order(session, user, order_id)
    if not value.strip():
        raise ValidationError("Result value is required.")
    _transition(order, LabOrderStatus.RESULTED.value)
    order.result_value = value.strip()[:255]
    order.result_notes = notes.strip() or None
    order.resulted_at = utcnow()
    audit.record(
        session,
        actor=user.username,
        actor_role=user.role.value,
        action="lab_result",
        resource="lab_order",
        resource_id=order.id,
    )
    session.commit()
    return order


def cancel_order(session: Session, user: CurrentUser, order_id: int, reason: str) -> LabOrder:
    user.require("lab:write")
    order = get_order(session, user, order_id)
    _transition(order, LabOrderStatus.CANCELLED.value)
    order.result_notes = f"cancelled: {reason.strip()}"
    session.commit()
    return order


def get_order(session: Session, user: CurrentUser, order_id: int) -> LabOrder:
    user.require("lab:read")
    order = session.get(LabOrder, order_id)
    if not order:
        raise NotFoundError(f"Lab order {order_id} not found.")
    enforce_patient_scope(user, order.patient_id)
    return order


def list_orders(
    session: Session, user: CurrentUser, *, patient_id: int | None = None, status: str | None = None
) -> List[LabOrder]:
    user.require("lab:read")
    stmt = select(LabOrder)
    if patient_id:
        enforce_patient_scope(user, patient_id)
        stmt = stmt.where(LabOrder.patient_id == patient_id)
    if status:
        stmt = stmt.where(LabOrder.status == status)
    return list(session.scalars(stmt.order_by(LabOrder.id.desc())))

